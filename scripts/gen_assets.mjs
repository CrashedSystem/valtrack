import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(repo, "assets");
// Snapshot of https://valorant-api.com/v1/agents?isPlayableCharacter=true so the
// name lookup is a file read at runtime instead of an HTTPS call.
const catalog = JSON.parse(readFileSync(join(root, "agents.json"), "utf8")).data;
// Codename -> display name. The match payload only ships the internal codename
// (`/Game/Maps/Plummet/Plummet`), so the table has to come from Riot's public
// map catalog. assetPath looks like `/Game/Maps/Plummet/Plummet_PrimaryAsset`.
const maps = JSON.parse(readFileSync(join(root, "maps.json"), "utf8")).data
  .map((m) => {
    const tail = (m.assetPath || "").split("/").filter(Boolean).pop() || "";
    const codename = tail.replace(/_PrimaryAsset$/, "");
    return { codename, name: m.displayName };
  })
  .filter((m) => m.codename && m.name)
  .sort((a, b) => a.codename.localeCompare(b.codename));
const agents = readdirSync(join(root, "agents"))
  .filter((f) => f.endsWith(".png"))
  .map((f) => f.slice(0, -4))
  .sort();
const ranks = readdirSync(join(root, "ranks"))
  .filter((f) => f.endsWith(".png"))
  .map((f) => f.slice(0, -4))
  .sort((a, b) => Number(a) - Number(b));

let out = `// @generated by scripts/gen_assets.mjs - do not edit by hand.
// Icons are embedded so the overlay never touches the network for artwork.

pub static AGENTS: &[(&str, &[u8])] = &[
`;
for (const uuid of agents) {
  out += `    ("${uuid}", include_bytes!("../assets/agents/${uuid}.png")),\n`;
}
out += `];

pub static RANKS: &[(i64, &[u8])] = &[
`;
for (const tier of ranks) {
  out += `    (${tier}, include_bytes!("../assets/ranks/${tier}.png")),\n`;
}
out += `];
`;

out += `
/// Agent UUID -> display name, embedded from the valorant-api snapshot.
pub static AGENT_NAMES: &[(&str, &str)] = &[
`;
for (const a of catalog) {
  if (!a.isPlayableCharacter) continue;
  const uuid = a.uuid.toLowerCase();
  if (agents.includes(uuid)) {
    out += `    ("${uuid}", "${a.displayName}"),\n`;
  }
}
out += `];
`;

out += `
/// Map codename -> display name, from the embedded valorant-api snapshot.
pub static MAPS: &[(&str, &str)] = &[
`;
for (const m of maps) {
  out += `    ("${m.codename}", "${m.name}"),\n`;
}
out += `];
`;

writeFileSync(join(repo, "src", "assets.rs"), out, "utf8");
console.log(
  `agents=${agents.length} names=${catalog.length} maps=${maps.length} ranks=${ranks.length} bytes=${out.length}`,
);
